"""Recipe -> Vagrantfile or Lima template, for hosts without Incus.

The provisioning script is the same one `petribox build` runs (_common.sh,
extras, provision.sh), so the tools match; the base image is the closest
Vagrant box or Lima template. Secrets, ephemeral copies and containers have
no equivalent there: the export is always a VM, set up from scratch.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from . import recipes

# Incus image alias (without the remote) -> (Vagrant box, Lima template).
# None: no maintained equivalent. A recipe can set its own with
# `vagrant_box = "..."` / `lima_template = "..."`.
IMAGES: dict[str, tuple[str | None, str | None]] = {
    "debian/12": ("bento/debian-12", "debian-12"),
    "debian/13": ("bento/debian-13", "debian-13"),
    "ubuntu/24.04": ("bento/ubuntu-24.04", "ubuntu-24.04"),
    "ubuntu/26.04": ("bento/ubuntu-26.04", "ubuntu-26.04"),
    "rockylinux/9": ("bento/rockylinux-9", "rocky-9"),
    "rockylinux/10": ("bento/rockylinux-10", "rocky-10"),
    "almalinux/10": ("bento/almalinux-10", "almalinux-10"),
    "fedora/43": ("bento/fedora-43", "fedora-43"),
    "fedora/44": ("bento/fedora-latest", "fedora-44"),
    "archlinux": ("boxen/archlinux-rolling", "archlinux"),
    "kali": ("kalilinux/rolling", None),
}


class ExportError(RuntimeError):
    """A recipe cannot be exported to the requested tool."""


def image_key(image: str) -> str:
    """'images:debian/13/cloud' -> 'debian/13'."""
    alias = image.split(":", 1)[-1]
    alias = re.sub(r"/(cloud|default)$", "", alias)
    return alias


def target_image(r: recipes.Recipe, tool: str) -> str:
    own = r.vagrant_box if tool == "vagrant" else r.lima_template
    if own:
        return own
    vagrant, lima = IMAGES.get(image_key(r.image), (None, None))
    found = vagrant if tool == "vagrant" else lima
    if not found:
        key = "vagrant_box" if tool == "vagrant" else "lima_template"
        raise ExportError(f"no known {tool} equivalent for image '{r.image}'; "
                          f"set `{key} = \"...\"` in the recipe")
    return found


def lima_base(name: str) -> str:
    """A bare name means Lima's image-only template (no host mounts)."""
    return name if ":" in name or "/" in name else f"template:_images/{name}"


def mebibytes(size: str) -> int:
    m = re.fullmatch(r"\s*(\d+)\s*([KMGT]i?B)?\s*", size)
    if not m:
        raise ExportError(f"cannot read size '{size}'")
    factor = {"K": 1 / 1024, "M": 1, "G": 1024, "T": 1024 * 1024}[(m.group(2) or "MB")[0]]
    return int(int(m.group(1)) * factor)


def notes(r: recipes.Recipe) -> list[str]:
    out = [f"Generated by petribox from recipe '{r.name}'" + (f": {r.description}" if r.description else "")]
    if not r.vm:
        out.append("The recipe is a container; this is a VM.")
    return out


def vagrant(r: recipes.Recipe) -> dict[str, str]:
    """Files for a Vagrant project directory."""
    head = "\n".join(f"# {line}" for line in notes(r))
    vagrantfile = f'''{head}
# Start: vagrant up    Enter: vagrant ssh    Remove: vagrant destroy
# The project directory is shared at /vagrant. Tools go to the `vagrant` user.
Vagrant.configure("2") do |config|
  config.vm.box = {json.dumps(target_image(r, "vagrant"))}
  config.vm.hostname = {json.dumps(r.name)}
  # Root disk size needs VAGRANT_EXPERIMENTAL=disks:
  # config.vm.disk :disk, size: {json.dumps(r.disk.replace("iB", "B"))}, primary: true
  ["virtualbox", "vmware_desktop", "parallels", "libvirt", "hyperv"].each do |provider|
    config.vm.provider provider do |vm|
      vm.cpus = {r.cpus}
      vm.memory = {mebibytes(r.memory)}
    end
  end
  config.vm.provision "shell", path: "provision.sh", env: {{ "PB_USER" => "vagrant" }}
end
'''
    return {"Vagrantfile": vagrantfile, "provision.sh": "#!/bin/bash\n" + r.script()}


def lima(r: recipes.Recipe) -> dict[str, str]:
    """A Lima template file (`limactl start ./NAME.yaml`)."""
    script = "#!/bin/bash\n" + 'export PB_USER="{{.User}}"\n' + r.script()
    if "{{" in r.script():
        # Lima expands {{...}} in provision scripts; ours must not contain any.
        raise ExportError(f"recipe '{r.name}' has '{{{{' in its scripts, which Lima would expand")
    body = "\n".join("    " + line if line else "" for line in script.splitlines())
    head = "\n".join(f"# {line}" for line in notes(r))
    template = f'''{head}
# Start: limactl start ./{r.name}.yaml    Enter: limactl shell {r.name}
# Remove: limactl delete -f {r.name}. Tools go to your own user, as in Lima.
# Image only: unlike Lima's usual templates, nothing from the host (not even
# your home directory) is mounted. To share a folder, add for example:
#   mounts: [{{location: "~/project", writable: true}}]
minimumLimaVersion: 2.0.0
base:
- {lima_base(target_image(r, "lima"))}
cpus: {r.cpus}
memory: {json.dumps(r.memory)}
disk: {json.dumps(r.disk)}
provision:
- mode: system
  script: |
{body}
'''
    return {f"{r.name}.yaml": template}


def export(r: recipes.Recipe, tool: str, out: Path, force: bool = False) -> list[Path]:
    files = vagrant(r) if tool == "vagrant" else lima(r)
    out.mkdir(parents=True, exist_ok=True)
    paths = [out / name for name in files]
    clash = [p for p in paths if p.exists()]
    if clash and not force:
        raise ExportError(f"{', '.join(map(str, clash))} exists; pass --force to overwrite")
    for path, text in zip(paths, files.values()):
        path.write_text(text)
        if path.suffix == ".sh":
            path.chmod(0o755)
    return paths
